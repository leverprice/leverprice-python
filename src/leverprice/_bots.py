# re.ASCII: case-insensitive like a JavaScript /i regex (no Unicode case folding).
BOT_USER_AGENT = re.compile("|".join(_BOT_PATTERNS), re.IGNORECASE | re.ASCII)


def is_bot(user_agent: Any) -> bool:
    """True for crawlers, link previewers, headless browsers, monitors and HTTP clients."""
    if not isinstance(user_agent, str):
        return False
    ua = js_trim(user_agent)
    return len(ua) > 0 and BOT_USER_AGENT.search(ua) is not None
